/** a tall soft bar standing on the ground (the texture is bright at its TOP, so it is flipped: bright at the foot, fading up) */
function bar(note: string, w: number, h: number, life: number, color: number[], extra: Partial<ParticleSpec> = {}): ParticleSpec {
  return one({
    note,
    life: [0, life],
    half: [[0, w / 2], [0, h / 2]],
    at: [0, h / 2 - 0.2, 0],
    color,
    billboard: 'upright',
    rotation: { start: [180, 180] },
    attach: true,
    blend: 'add',
    tex: ART_PILLAR_FADE,
    ...extra,
  });
}

