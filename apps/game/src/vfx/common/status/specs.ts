/** emitter path that goes once round a circle of radius `r` per `cycle` s (a key every 22.5 deg): with rate = N / life the N alive particles are born evenly spaced
 *  round the head, so the stars never bunch into one crown (random ellipse births did) */
function circle(r: number, cycle: number, phase = 0): NonNullable<ParticleSpec['path']> {
  const n = 16;
  const x: number[] = [];
  const z: number[] = [];
  for (let i = 0; i <= n; i++) {
    const a = phase + (i / n) * Math.PI * 2;
    x.push(+((i / n) * cycle).toFixed(4), +(Math.cos(a) * r).toFixed(4));
    z.push(+((i / n) * cycle).toFixed(4), +(Math.sin(a) * r).toFixed(4));
  }
  return { x, z };
}





