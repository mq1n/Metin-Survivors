/** one random frame per puff: billowing masses, soft dark masses and grainy clumps (all straight alpha) */
const SMOKE_BODY: ArtTex = { art: ['vfx_smoke_lumpball_a', 'vfx_puff_energy_dark_a', 'vfx_smoke_dustclump_a'], fallback: 'smoke2' };

/** shared defaults of the particle elements below (an element states only what differs) */
const P = { kind: 'particle' as const, cycle: 0.5, max: 1, rate: [0, 60] as readonly number[], life: [0, 0.5] as readonly number[] };

export function el(e: Omit<ParticleSpec, 'kind' | 'cycle' | 'max' | 'rate' | 'life'> & Partial<Pick<ParticleSpec, 'cycle' | 'max' | 'rate' | 'life'>>): ParticleSpec {
  return { ...P, ...e };
}

/** lifts every camera-facing / upright element to height `y` (a billboard centred on the floor is cut in half by the ground plane); ground-lying
 *  elements stay on the floor, elements that already state an `at` keep it */
function raised(list: readonly ElementSpec[], y: number): ElementSpec[] {
  return list.map((e) => {
    if (e.kind !== 'particle' || e.billboard === 'ground' || e.at !== undefined) return e;
    return { ...e, at: [0, y, 0] as const };
  });
}

