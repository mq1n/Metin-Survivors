/** a ground-lying sprite born once at t0 and held for `life` s (alpha envelope in the colour curve) */
function ground(b: Omit<Parameters<typeof burst>[0], 'billboard'>): ParticleSpec {
  return burst({ ...b, billboard: 'ground', attach: b.attach ?? true });
}

/** a screen-facing sprite (a column / head / shaft that must keep its full height in the game camera) */
function card(b: Parameters<typeof burst>[0]): ParticleSpec {
  return burst({ ...b, billboard: 'screen', attach: b.attach ?? true });
}

/** persistent ground layer: ONE long-lived particle (born at once, rotation aligned with its siblings by `start: [0, 0]`, fade-in 0.25 s, no
 *  fade-out until it is stopped) - the r1 pulses started at alpha 0 and left the first 0.6 s empty. `life` s of the particle = 2 min. */
const LOOP_LIFE = 120;
const fadeIn = (hex: number, a: number, hexEnd = hex): number[] => [0, hex, 0, 0.1 / LOOP_LIFE, hex, a, 0.97, hexEnd, a, 1, hexEnd, 0];
function loopGround(b: Omit<Parameters<typeof burst>[0], 'billboard' | 'life' | 'cycle' | 'loops' | 'max' | 'rate'>): ParticleSpec {
  return ground({ ...b, cycle: 4, loops: 0, max: 1, rate: [0, 60], life: [0, LOOP_LIFE] });
}

