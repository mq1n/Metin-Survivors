// Self / ally effects of the player-feedback target as FxSpecs: aura.ring, buff.aura, dash.streak (spec sk.gen.pf_dash), summon.circle /

// Rules every spec here follows (REPORT §5): layered soft sprites (no vector rings / hard cylinders), ground-anchored, body-height
// only where it must be, 2.5-3 m+ wide so it survives next to the hero ring, saturated colour, one hero shape per event, short
// (<= 1.6 s), each effect its own sprite family (no shared rune stamp). The hero guard (vfx/heroGuard.ts) fades everything over the
// hero's body ellipse to 35 %, so the shapes live AROUND the body (rings, shafts, motes), not in it.
//
// r2 (2026-10-20) lessons from the blind critic of r1, applied to every spec below:

//    additive pale layers changed 2-4 % of a snow frame and vanished; the twin carries the hue, the additive layer the hot core;
//  - upright billboards are foreshortened to half their height by the game camera (pitch ~60 deg), so shafts / columns / heads are SCREEN
//    billboards whose bottom edge stays above the floor (yc >= 0.55 * half height: no ground clipping);
//  - no ring of dashes / spikes sprites (they render as a ring of fuzzy squares): rings are soft bands or bold broken arcs;
//  - no pink / pale gold washes over the hero: colour keys stay on one hue family (gold -> amber, lilac -> violet, green -> blue).
