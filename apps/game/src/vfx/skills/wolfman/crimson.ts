function claw(o: {
  t0?: number;
  col: number;
  /** colour at the end of the visible window (wildattack_03 turns teal → mint → yellow) */
  col2?: number;
  r?: number;
  life?: number;
  spin?: number;
  start?: number;
  at?: Vec3;
  alpha?: number;
  attach?: boolean;
  loops?: number;
  cycle?: number;
  place?: 'target';
  rake?: boolean;
  note?: string;
}): ParticleSpec {
  const a = o.alpha ?? 1;
  const c2 = o.col2 ?? o.col;
  // the crescent sits at ~0.4 of the quad half-size and peaks at scale 1.9
  const h = (o.r ?? 1.1) / 0.76;
  const cyc = o.cycle ?? 0.1;
  return {
    kind: 'particle',
    note: o.note ?? 'cheonryongchuta_blow crescent, lie billboard, rotation -4000 -> -1000 deg/s',
    t0: o.t0 ?? 0,
    cycle: cyc,
    ...(o.loops !== undefined ? { loops: o.loops } : {}),
    max: 2,
    // looped swipes burst once per cycle: hold the rate for ~2 frames (a shorter key is skipped at 60 fps)
    rate: cyc > 0.1 ? [0, 300, 0.04, 300, 0.05, 0] : [0, 300],
    life: [0, o.life ?? 0.24],
    at: o.at ?? [0, 1.0, 0],
    ...(o.place ? { place: o.place } : {}),
    half: [0, h],
    scale: [[0, 0.3, 0.5, 1.9, 1, 2.6], [0, 0.3, 0.5, 1.9, 1, 0.6]],
    color: [0, o.col, 0, 0.12, o.col, a, 0.55, c2, a * 0.75, 1, c2, 0],
    billboard: 'ground',
    rotation: { start: [o.start ?? 0, (o.start ?? 0) + 20], spin: o.spin ?? -2500 },
    ...(o.attach ? { attach: true } : {}),
    blend: 'add',
    bright: 1.3,
    tex: o.rake ? 'clawArcs' : 'crescentGlow',
  };
}




