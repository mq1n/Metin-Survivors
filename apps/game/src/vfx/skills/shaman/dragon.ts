/** pokroe_c colours (white / lilac / blue / violet) → the yongpa_4 + meteo fire ramp (white / gold / orange / red) */
function fireTint(c: readonly number[]): number[] {
  const MAP: Record<number, number> = {
    0xffffff: 0xffffff, 0xf0e0ff: 0xffe8b0, 0xa080ff: 0xff7a30, 0xc8c0ff: 0xffc890, 0x8078e0: 0xff8a40, 0x4841bc: 0xa02808,
    0x8eacff: 0xffb050, 0x4b52d3: 0xd04010, 0xcfeaff: 0xfff0c0, 0x87d4ff: 0xffb060, 0xa070ff: 0xffa040, 0x5e32ab: 0xc03010,
    0xd8e8ff: 0xfff0d0, 0x80a8ff: 0xffa050, 0x4f6dbf: 0xb03810,
  };
  return c.map((v, i) => (i % 3 === 1 ? (MAP[v] ?? v) : v));
}

